CREATE DATABASE IF NOT EXISTS biblioteca_orm CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE biblioteca_orm;
CREATE TABLE IF NOT EXISTS autores (
 id INT AUTO_INCREMENT PRIMARY KEY,
 nome VARCHAR(120) NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS livros (
 id INT AUTO_INCREMENT PRIMARY KEY,
 titulo VARCHAR(150) NOT NULL,
 ano INT NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS livros_autores (
 livro_id INT NOT NULL,
 autor_id INT NOT NULL,
 PRIMARY KEY (livro_id, autor_id),
 FOREIGN KEY (livro_id) REFERENCES livros(id) ON DELETE RESTRICT,
 FOREIGN KEY (autor_id) REFERENCES autores(id) ON DELETE RESTRICT
) ENGINE=InnoDB;
